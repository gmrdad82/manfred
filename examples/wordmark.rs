use std::process::ExitCode;

use manfred_scene::fonts::BOLD;
use ttf_parser::{Face, OutlineBuilder, Rect};

const WORD: &str = "Manfred";
const AMBER: &str = "#F2BF58";
const EM: f64 = 1000.0;
const BASELINE: f64 = 1000.0;
const GAP_RATIO: f64 = 0.5;
const SIZE: f64 = 36.0;
const USAGE: &str = "usage: wordmark word --out <file.svg>\n       wordmark lockup --mark <mark.svg> --out <file.svg> [--size <px>] [--mark-scale <times the cap height>]";

fn num(value: f64, decimals: usize) -> String {
    let text = format!("{value:.decimals$}");
    match text.strip_prefix('-') {
        Some(rest) if rest.bytes().all(|b| b == b'0' || b == b'.') => rest.to_string(),
        _ => text,
    }
}

struct Path {
    scale: f64,
    pen: f64,
    d: String,
    cubic: bool,
}

impl Path {
    fn point(&self, x: f32, y: f32) -> String {
        format!(
            "{} {}",
            num(self.pen + f64::from(x) * self.scale, 2),
            num(BASELINE - f64::from(y) * self.scale, 2)
        )
    }

    fn command(&mut self, letter: char, points: &[(f32, f32)]) {
        if !self.d.is_empty() && !self.d.ends_with('Z') {
            self.d.push(' ');
        }
        self.d.push(letter);
        let text: Vec<String> = points.iter().map(|(x, y)| self.point(*x, *y)).collect();
        self.d.push_str(&text.join(" "));
    }
}

impl OutlineBuilder for Path {
    fn move_to(&mut self, x: f32, y: f32) {
        self.command('M', &[(x, y)]);
    }

    fn line_to(&mut self, x: f32, y: f32) {
        self.command('L', &[(x, y)]);
    }

    fn quad_to(&mut self, x1: f32, y1: f32, x: f32, y: f32) {
        self.command('Q', &[(x1, y1), (x, y)]);
    }

    fn curve_to(&mut self, _: f32, _: f32, _: f32, _: f32, _: f32, _: f32) {
        self.cubic = true;
    }

    fn close(&mut self) {
        self.d.push('Z');
    }
}

struct Word {
    d: String,
    ink: [f64; 4],
    cap: f64,
    x_height: f64,
}

fn union(ink: &mut Option<[f64; 4]>, rect: [f64; 4]) {
    *ink = Some(match *ink {
        None => rect,
        Some(old) => [
            old[0].min(rect[0]),
            old[1].min(rect[1]),
            old[2].max(rect[2]),
            old[3].max(rect[3]),
        ],
    });
}

fn outline() -> Result<Word, String> {
    let face = Face::parse(BOLD, 0).map_err(|e| format!("the embedded Bold font: {e}"))?;
    let scale = EM / f64::from(face.units_per_em());
    let mut path = Path {
        scale,
        pen: 0.0,
        d: String::new(),
        cubic: false,
    };
    let mut ink = None;
    for letter in WORD.chars() {
        let glyph = face
            .glyph_index(letter)
            .ok_or_else(|| format!("the font has no glyph for {letter:?}"))?;
        let Rect {
            x_min,
            y_min,
            x_max,
            y_max,
        } = face
            .outline_glyph(glyph, &mut path)
            .ok_or_else(|| format!("the glyph {letter:?} has no outline"))?;
        let advance = f64::from(
            face.glyph_hor_advance(glyph)
                .ok_or_else(|| format!("the glyph {letter:?} has no advance"))?,
        );
        union(
            &mut ink,
            [
                path.pen + f64::from(x_min) * scale,
                BASELINE - f64::from(y_max) * scale,
                path.pen + f64::from(x_max) * scale,
                BASELINE - f64::from(y_min) * scale,
            ],
        );
        path.pen += advance * scale;
    }
    if path.cubic {
        return Err("the font has a cubic outline, which the wordmark does not write".into());
    }
    let cap = face
        .capital_height()
        .ok_or("the font has no capital height")?;
    let x_height = face.x_height().ok_or("the font has no x-height")?;
    Ok(Word {
        d: path.d,
        ink: ink.ok_or("the word has no ink")?,
        cap: f64::from(cap) * scale,
        x_height: f64::from(x_height) * scale,
    })
}

fn word_svg() -> Result<String, String> {
    let word = outline()?;
    let [x0, y0, x1, y1] = word.ink;
    let (width, height) = (x1 - x0, y1 - y0);
    Ok(format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"{} {} {} {}\" width=\"{}\" height=\"{}\">\n\
<!-- The Manfred wordmark: JetBrains Mono Nerd Font Bold, letter-spacing 0, outlined from the font at {} px, baseline at y {}; generated by Manfred's wordmark example, never hand-edited. -->\n\
<path fill=\"{AMBER}\" d=\"{}\"/>\n\
</svg>\n",
        num(x0, 2),
        num(y0, 2),
        num(width, 2),
        num(height, 2),
        num(SIZE * width / height, 3),
        num(SIZE, 0),
        num(EM, 0),
        num(BASELINE, 2),
        word.d
    ))
}

struct Mark {
    inner: String,
    origin: [f64; 2],
    size: [f64; 2],
}

fn strip_comments(text: &str) -> String {
    let mut out = String::new();
    let mut rest = text;
    while let Some(start) = rest.find("<!--") {
        out.push_str(&rest[..start]);
        match rest[start..].find("-->") {
            Some(end) => rest = &rest[start + end + 3..],
            None => return out,
        }
    }
    out.push_str(rest);
    out
}

fn attribute(tag: &str, name: &str) -> Option<String> {
    let key = format!(" {name}=\"");
    let start = tag.find(&key)? + key.len();
    let end = tag[start..].find('"')?;
    Some(tag[start..start + end].to_string())
}

fn parse_mark(svg: &str) -> Result<Mark, String> {
    let svg = strip_comments(svg);
    let open = svg.find("<svg").ok_or("the mark has no <svg> element")?;
    let close = open
        + svg[open..]
            .find('>')
            .ok_or("the mark's <svg> tag is not closed")?;
    let tag = &svg[open..close];
    let end = svg.rfind("</svg>").ok_or("the mark has no </svg>")?;
    let view = attribute(tag, "viewBox").ok_or("the mark has no viewBox")?;
    let numbers = view
        .split([' ', ','])
        .filter(|part| !part.is_empty())
        .map(|part| part.parse::<f64>().map_err(|e| format!("the viewBox: {e}")))
        .collect::<Result<Vec<_>, _>>()?;
    let [x, y, w, h] = numbers[..] else {
        return Err("the mark's viewBox wants four numbers".into());
    };
    if w <= 0.0 || h <= 0.0 {
        return Err("the mark's viewBox is empty".into());
    }
    let inner = svg[close + 1..end]
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty())
        .collect::<Vec<_>>()
        .join("\n");
    Ok(Mark {
        inner,
        origin: [x, y],
        size: [w, h],
    })
}

fn lockup_svg(mark: &str, size: f64, times: f64) -> Result<String, String> {
    if size <= 0.0 {
        return Err("the size wants a positive number".into());
    }
    if !(times.is_finite() && times > 0.0) {
        return Err("the mark scale wants a positive number".into());
    }
    let mark = parse_mark(mark)?;
    let word = outline()?;
    let k = size / EM;
    let [ink_left, ink_top, ink_right, ink_bottom] = word.ink;
    let word_width = (ink_right - ink_left) * k;
    let word_height = (ink_bottom - ink_top) * k;
    let cap = word.cap * k;
    let gap = GAP_RATIO * word_height;
    let mark_height = cap * times;
    let mark_scale = mark_height / mark.size[1];
    let mark_width = mark.size[0] * mark_scale;

    let band = BASELINE - word.x_height / 2.0;
    let centre = (band - BASELINE) * k;
    let word_top = (ink_top - BASELINE) * k;
    let word_bottom = (ink_bottom - BASELINE) * k;
    let mark_top = centre - mark_height / 2.0;
    let mark_bottom = centre + mark_height / 2.0;
    let top = word_top.min(mark_top);
    let bottom = word_bottom.max(mark_bottom);
    let height = bottom - top;
    let baseline = -top;
    let mark_y = baseline + mark_top;
    let word_x = mark_width + gap;
    let width = word_x + word_width;

    let mark_tx = -mark.origin[0] * mark_scale;
    let mark_ty = mark_y - mark.origin[1] * mark_scale;
    let word_tx = word_x - ink_left * k;
    let word_ty = baseline - BASELINE * k;

    Ok(format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 {w} {h}\" width=\"{w}\" height=\"{h}\">\n\
<!-- The Manfred lockup at 1x: mark {mark_h} px, {height_text}, at (0.000,{my}), gap {gap_text} px ({ratio} of the word's {word_h} px height), the word JetBrains Mono Nerd Font Bold {font} at x {wx}, baseline y {base}, the mark centred on the x-height band at y {band_y}; generated by Manfred's wordmark example, never hand-edited. -->\n\
<g transform=\"translate({mtx} {mty}) scale({ms})\">\n\
{inner}\n\
</g>\n\
<path fill=\"{AMBER}\" transform=\"translate({wtx} {wty}) scale({ws})\" d=\"{d}\"/>\n\
</svg>\n",
        w = num(width, 3),
        h = num(height, 3),
        mark_h = num(mark_height, 3),
        height_text = if times == 1.0 {
            "the word's cap height".to_string()
        } else {
            format!("{} times the word's cap height", num(times, 2))
        },
        my = num(mark_y, 3),
        gap_text = num(gap, 3),
        ratio = num(GAP_RATIO, 2),
        word_h = num(word_height, 3),
        font = num(size, 0),
        wx = num(word_x, 3),
        base = num(baseline, 3),
        band_y = num(baseline + centre, 3),
        mtx = num(mark_tx, 3),
        mty = num(mark_ty, 3),
        ms = num(mark_scale, 5),
        inner = mark.inner,
        wtx = num(word_tx, 3),
        wty = num(word_ty, 3),
        ws = num(k, 5),
        d = word.d,
    ))
}

fn option(args: &[String], name: &str) -> Option<String> {
    let at = args.iter().position(|a| a == name)?;
    args.get(at + 1).cloned()
}

fn run(args: &[String]) -> Result<(), String> {
    let out = option(args, "--out").ok_or(USAGE)?;
    let svg = match args.first().map(String::as_str) {
        Some("word") => word_svg()?,
        Some("lockup") => {
            let path = option(args, "--mark").ok_or(USAGE)?;
            let mark =
                std::fs::read_to_string(&path).map_err(|e| format!("cannot read {path}: {e}"))?;
            let size = match option(args, "--size") {
                Some(text) => text.parse::<f64>().map_err(|e| format!("--size: {e}"))?,
                None => SIZE,
            };
            let times = match option(args, "--mark-scale") {
                Some(text) => text
                    .parse::<f64>()
                    .map_err(|e| format!("--mark-scale: {e}"))?,
                None => 1.0,
            };
            lockup_svg(&mark, size, times)?
        }
        _ => return Err(USAGE.into()),
    };
    std::fs::write(&out, svg).map_err(|e| format!("cannot write {out}: {e}"))
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match run(&args) {
        Ok(()) => ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("wordmark: {message}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const CIRCLE: &str = "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 96 96\" width=\"96\" height=\"96\">\n  <!-- a test mark -->\n  <circle cx=\"48\" cy=\"48\" r=\"40\" fill=\"#DE4600\"/>\n</svg>\n";

    struct Count(usize);

    impl OutlineBuilder for Count {
        fn move_to(&mut self, _: f32, _: f32) {
            self.0 += 1;
        }
        fn line_to(&mut self, _: f32, _: f32) {}
        fn quad_to(&mut self, _: f32, _: f32, _: f32, _: f32) {}
        fn curve_to(&mut self, _: f32, _: f32, _: f32, _: f32, _: f32, _: f32) {}
        fn close(&mut self) {}
    }

    #[test]
    fn the_word_has_one_path_for_each_contour_of_its_glyphs() {
        let face = Face::parse(BOLD, 0).unwrap();
        let mut count = Count(0);
        for letter in WORD.chars() {
            let glyph = face.glyph_index(letter).unwrap();
            face.outline_glyph(glyph, &mut count).unwrap();
        }
        let svg = word_svg().unwrap();
        assert_eq!(svg.matches("<path").count(), 1);
        let d = svg.split(" d=\"").nth(1).unwrap();
        assert_eq!(d.matches('M').count(), count.0);
        assert_eq!(d.matches('Z').count(), count.0);
    }

    #[test]
    fn two_runs_give_the_same_bytes() {
        assert_eq!(word_svg().unwrap(), word_svg().unwrap());
        assert_eq!(
            lockup_svg(CIRCLE, 36.0, 1.0).unwrap(),
            lockup_svg(CIRCLE, 36.0, 1.0).unwrap()
        );
    }

    #[test]
    fn the_lockup_places_the_mark_through_a_group_and_has_no_by() {
        let svg = lockup_svg(CIRCLE, 36.0, 1.0).unwrap();
        assert!(svg.contains("<g transform=\"translate("));
        assert!(svg.contains("<circle"));
        assert!(!svg.contains("a test mark"));
        assert!(!svg.contains("<text"));
    }

    #[test]
    fn a_mark_without_a_view_box_is_refused() {
        assert!(lockup_svg("<svg><circle/></svg>", 36.0, 1.0).is_err());
    }

    #[test]
    fn numbers_never_print_a_negative_zero() {
        assert_eq!(num(-0.0001, 3), "0.000");
        assert_eq!(num(-1.5, 2), "-1.50");
    }
}
